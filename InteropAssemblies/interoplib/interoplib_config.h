// LEDTREES: параметры вывода на ленту. Пины SPI и число пикселей приходят из
// managed-кода в NativeInit — здесь только то, что зашито в прошивку.
#define SPI_LEDS_FREQ_HZ        2500000

// Геометрия кадра. Обязана совпадать с managed interoplib.FrameGeometry
// (Pixels/Channels/BytesPerPixel) — общего источника через границу interop нет.
// MAX_PIXELS — потолок ленты (валидируется в NativeInit); фактический pixelCount
// приходит из managed и может быть меньше.
#define MAX_PIXELS              400
#define STRIPS_CNT              4
#define BYTES_PER_PIXEL         3
#define BUFF_SIZE               (STRIPS_CNT * MAX_PIXELS * BYTES_PER_PIXEL)

// Выходная цветокоррекция под WS2812 (ledtrees-esp32 docs/color-filters.md):
// гамма + чёрная точка + баланс белого, свёрнутые в три таблицы канал→байт
// (см. outputLut). Пока зашито константами — interop-управление добавится
// отдельной фазой и будет просто перезаписывать таблицы, эти значения станут
// дефолтом при старте.
//
// OUTPUT_GAMMA — WS2812 линейны по PWM, глаз — нет: без гаммы низы «выгорают»,
//   фейды и градиенты грязные. 2.2 — стандартная стартовая точка (подбирается).
// OUTPUT_BLACK_POINT — входной порог (после яркости): значения <= порога → чистый
//   0. Гасит едва тлеющие мерцающие пиксели от шума камеры в тёмных сценах.
// OUTPUT_WB_* — per-channel gain Q8 (256 = ×1.0): свести белый партии ленты /
//   нескольких ёлок. Дефолт нейтральный — подбирается по факту на живой ленте.
//
// Идентичность (байт-в-байт прежний вывод): GAMMA 1.0f, BLACK_POINT 0, WB 256.
#define OUTPUT_GAMMA            2.2f
#define OUTPUT_BLACK_POINT      2
#define OUTPUT_WB_R             256
#define OUTPUT_WB_G             256
#define OUTPUT_WB_B             256

// Пропуск отправки неизменившегося кадра. Каждый ре-латч перезапускает
// внутренний PWM-цикл кристалла WS2812; на низкой скважности (значения 1–3,
// куда гамма кладёт тусклые цвета) обрезка PWM-периода — большая относительная
// ошибка, и статичный контент при постоянной перезаливке заметно «дребезжит»
// (однократно залитый — нет). Поэтому идентичный кадр не шлём вовсе; раз в
// столько кадров — страховочный ре-латч, чтобы случайный помеховый глитч
// пикселя не висел на ленте бесконечно (одиночный ре-латч раз в ~2 с глазу не
// виден, в отличие от дребезга на частоте кадров). 0 — слать всегда (как раньше).
#define OUTPUT_REFRESH_FRAMES   64

#define PROGRAM_TRANSITION_FPS  30

// Потолок темпа ВЫВОДА кадров на ленту (Гц). Продвижение по кадрам программы
// (contentFps = fps с учётом скорости) развязано от темпа вывода: до потолка
// outputFps==contentFps и лента идёт кадр-в-кадр как раньше, а выше — вывод
// держится на потолке, а по кадрам программы шагаем дробным аккумулятором
// (пропуск кадров). Так разгон скоростью не заказывает недостижимый железом темп.
// Потолок задан бюджетом SPI-кадра: 400 px = 4800 байт на 2.5 МГц ≈ 15 мс (+ latch)
// укладывается в период 60 fps (16,67 мс); выше лента физически не выводит.
#define LED_OUTPUT_FPS_MAX      60

// Кадров в буфере воспроизведения. ДОЛЖНО быть >= managed-кэпа предзагрузки
// (ProgramCache.MaxPrepareFrames): NativePrepareForPlay отвергает frame >= этого
// числа молча (S_FALSE).
#define BUFFER_FRAMES_COUNT     50
