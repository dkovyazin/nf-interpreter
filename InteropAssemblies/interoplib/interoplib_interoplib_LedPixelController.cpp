// Runtime colour correction (ledtrees-esp32 docs/color-filters.md, phase 3):
// parameters rather than a table, since the native side applies the brightness
// before the gamma itself. gammaQ8 == 0 resets to the compile time defaults;
// out of range values are rejected silently by the component (S_FALSE), and the
// managed wrapper validates the same bounds up front.
void LedPixelController::NativeSetOutputCorrection( uint16_t gammaQ8, uint8_t blackPoint, uint16_t wbR, uint16_t wbG, uint16_t wbB, int16_t contrastQ8, HRESULT &hr )
{
    hr = ToHResult(lt_led_set_output_correction(gammaQ8, blackPoint, wbR, wbG, wbB, contrastQ8));
}

// Statistics for composing a playback frame since the last call, packed as
// (avg << 16) | max in microseconds; 0 means there were no frames. This is
// diagnostics: the IDF logs are compiled out of the firmware, so the native side
// accumulates and the managed side logs.
signed int LedPixelController::NativeGetComposeStats( HRESULT &hr )
{
    hr = S_OK;
    return lt_led_get_compose_stats();
}

// Re-anchoring SyncPlay: check our own position against the frame the group is
// playing right now. Returns the correction applied, in frames; 0 means we are
// in phase, or a very close correction is already under way.
signed int LedPixelController::NativeSyncPlayPosition( uint16_t groupFrame, HRESULT &hr )
{
    hr = S_OK;
    return lt_led_sync_play_position(groupFrame);
}

