//-----------------------------------------------------------------------------
//
// LEDTREES: adapter from the LedPixelController stubs to the ledtrees_ledpixel
// component.
//
// The whole output path to the strip (SPI, the LedTask and FeedTask tasks, the
// playback buffers, feeding from SD, the remap and the colour correction) lives
// in a separate IDF component - the ledtrees-idf-components repository,
// components/ledtrees_ledpixel. What is left here is unwrapping the managed
// arrays into a pointer and a size, and translating lt_led_status_t into an
// HRESULT.
//
// This implementation is written by hand, unlike interoplib.cpp/.h and
// *_mshl.cpp - those are generated by building the managed project and come
// ready in ledtrees-esp32/nanoframework/src/interoplib/Stubs/interoplib. They
// have to be copied from there rather than edited here: the method_lookup table
// is indexed by the ordinal of the method in the assembly, so a hand written
// insertion shifts the indices and calls end up in the wrong slots.
//
//-----------------------------------------------------------------------------

#include "interoplib.h"
#include "interoplib_interoplib_LedPixelController.h"

#include <ledtrees_ledpixel.h>

using namespace interoplib::interoplib;

// LT_LED_ERR_STATE is the former S_FALSE (the state does not allow it) and
// LT_LED_ERR_PARAM the former CLR_E_INVALID_PARAMETER (the arguments do not add
// up). The split is the same as it was in the body of each method before the
// code was moved out.
static HRESULT ToHResult(lt_led_status_t status)
{
    switch (status)
    {
        case LT_LED_OK:
            return S_OK;
        case LT_LED_ERR_PARAM:
            return CLR_E_INVALID_PARAMETER;
        default:
            return S_FALSE;
    }
}

void LedPixelController::NativeInit(
    signed int mosiPin,
    signed int misoPin,
    signed int clkPin,
    signed int csPin,
    signed int pixelCount,
    uint8_t red,
    uint8_t green,
    uint8_t blue,
    uint8_t powerLimitPercent,
    HRESULT &hr)
{
    lt_led_config_t config;
    config.mosiPin = mosiPin;
    config.misoPin = misoPin;
    config.clkPin = clkPin;
    config.csPin = csPin;
    config.pixelCount = pixelCount;
    config.initRed = red;
    config.initGreen = green;
    config.initBlue = blue;
    // The power limiter, as the factory fraction from the assembly configuration
    // (ledtrees-esp32 docs/assembly.md); the component reads 0 or anything >= 100
    // as "no limiter".
    config.powerLimitPercent = powerLimitPercent;

    hr = ToHResult(lt_led_init(&config));
}

void LedPixelController::NativeSetSource(
    CLR_RT_TypedArray_UINT8 path,
    unsigned int header,
    uint16_t frameSize,
    uint16_t countFrames,
    uint16_t startFrame,
    HRESULT &hr)
{
    hr = ToHResult(
        lt_led_set_source(path.GetBuffer(), path.GetSize(), header, frameSize, countFrames, startFrame));
}

