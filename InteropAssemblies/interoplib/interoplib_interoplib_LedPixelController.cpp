// NOTE on the contract: this writes the buffer that is NOT playing, without a
// Stop or Join and without any locking - during playback the same data is
// maintained by the feeding task. It is only safe when called on a STOPPED
// player. At the moment the managed side does not call this entry point at all
// (the LedPixelController.WriteToPlayBuffer wrapper has no callers).
